function grantRepeatableInfUpgrade(number) {
  return () => {
    if (number === 0) {
      // Tickspeed scaling
      player.infinityRebuyables[0] = Math.min(player.infinityRebuyables[0] + 1, 8);
    } else if (number === 1) {
      // Dimension scaling
      player.infinityRebuyables[1] = Math.min(player.infinityRebuyables[1] + 1, 7);
    } else if (number === 2) {
      // IP Generator
      player.infinityRebuyables[2] = Math.min(player.infinityRebuyables[2] + 1, 10);
    }
    GameCache.dimensionMultDecrease.invalidate();
  };
}

function grantAchievement(n) {
  return () => {
    const ach = Achievement(n);
    player.achievementBits[ach.row - 1] |= ach._bitmask;
  };
}

function grantInfUpgrade(name) {
  return () => {
    if (player.infinityUpgrade.has(name)) {
      player.celestials.ra.charged.add(name);
    } else {
      player.infinityUpgrade.add(name);
    }
  };
}

function grantEternityUpgrade(number) {
  return () => {
    player.eternityUpgrades.add(number);
  };
}

function grantDilationUpgrade(number) {
  return () => {
    player.dilation.upgrades.add(number);
  };
}

function grantNormalChallenge(int) {
  return () => {
    player.challenge.normal.completedBits |= 1 << int;
  };
}

function grantInfinityChallenge(int) {
  return () => {
    player.challenge.infinity.completedBits |= 1 << int;
  };
}

function grantEternityChallenge(challenge) {
  return () => {
    player.eternityChalls[challenge] += 1;
  };
}
